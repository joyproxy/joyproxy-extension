function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, k) => (params[k] == null ? "" : String(params[k])));
}

function lookup(key) {
  const table = TABLES[current] || EN;
  if (table[key] != null) return table[key];
  if (EN[key] != null) return EN[key];
  return key;
}

export function t(key, params) {
  const text = lookup(key);
  if (!params) return text;
  const resolved = { ...params };
  for (const [k, v] of Object.entries(params)) {
    if (k.endsWith("Key") && v) resolved[k.slice(0, -3)] = interpolate(lookup(v), params);
  }
  return interpolate(text, resolved);
}

export function formatLog(log) {
  if (!log) return "";
  if (log.key) return t(log.key, log.params || {});
  return log.text || "";
}

export function applyI18n(root = document) {
  const lang = current === "en" ? "en" : current;
  if (root.documentElement) root.documentElement.lang = lang;
  else document.documentElement.lang = lang;
  const scope = root.documentElement ? root : root;
  const titleKey = (root.documentElement || document.documentElement)?.dataset?.i18nTitle;
  if (titleKey && typeof document !== "undefined") document.title = t(titleKey);
  for (const el of scope.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of scope.querySelectorAll("[data-i18n-placeholder]")) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of scope.querySelectorAll("[data-i18n-tip]")) {
    el.setAttribute("data-tip", t(el.dataset.i18nTip));
  }
  for (const el of scope.querySelectorAll("[data-i18n-aria]")) {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  }
}
