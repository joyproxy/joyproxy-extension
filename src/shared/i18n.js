const TABLES = { "zh-CN": ZH_CN, "zh-TW": ZH_TW, en: EN };

let current = "en";
let preference = "auto";

export const UI_LOCALE_OPTIONS = [
  { id: "auto", native: "Follow browser" },
  { id: "en", native: "English" },
  { id: "zh-CN", native: "简体中文" },
  { id: "zh-TW", native: "繁體中文" },
];

function localeCandidates() {
  const out = [];
  try {
    if (typeof chrome !== "undefined" && chrome.i18n?.getUILanguage) {
      out.push(chrome.i18n.getUILanguage());
    }
  } catch {
    /* ignore */
  }
  if (typeof navigator !== "undefined") {
    if (navigator.language) out.push(navigator.language);
    if (Array.isArray(navigator.languages)) out.push(...navigator.languages);
  }
  return out.filter(Boolean);
}

function matchSupportedLocale(tag) {
  const lang = String(tag || "")
    .toLowerCase()
    .replace(/_/g, "-");
  if (!lang) return "";
  if (lang === "zh-tw" || lang === "zh-hk" || lang === "zh-mo" || lang.startsWith("zh-hant")) return "zh-TW";
  if (lang === "zh-cn" || lang === "zh-sg" || lang === "zh" || lang.startsWith("zh-hans") || lang.startsWith("zh-")) {
    return "zh-CN";
  }
  if (lang === "en" || lang.startsWith("en-")) return "en";
  return "";
}

export function browserLocale() {
  for (const tag of localeCandidates()) {
    const hit = matchSupportedLocale(tag);
    if (hit) return hit;
  }
  return "en";
}

export function resolveLocale(setting) {
  if (setting === "en" || setting === "zh-CN" || setting === "zh-TW") return setting;
  return browserLocale();
}

export function setLocale(setting) {
  preference = setting || "auto";
  current = resolveLocale(preference);
  return current;
}

export function activeLocale() {
  return current;
}

export function t(key) {
  const table = TABLES[current] || ZH_CN;
  return table[key] || ZH_CN[key] || key;
}

export function applyI18n(root = document) {
  const lang = current === "en" ? "en" : current;
  if (root.documentElement) root.documentElement.lang = lang;
  else document.documentElement.lang = lang;
  const scope = root.documentElement ? root : root;
  for (const el of scope.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of scope.querySelectorAll("[data-i18n-placeholder]")) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of scope.querySelectorAll("[data-i18n-tip]")) {
    el.setAttribute("data-tip", t(el.dataset.i18nTip));
  }
  for (const el of scope.querySelectorAll("[data-i18n-aria]")) {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  }
}
